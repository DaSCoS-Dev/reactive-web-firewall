/*
 * Release a regex compiled through ap_regcomp().
 */
static apr_status_t rwf_regex_cleanup(void *data)
{
    ap_regex_t *regex = (ap_regex_t *) data;

    if (regex != NULL) {
        ap_regfree(regex);
    }

    return APR_SUCCESS;
}


/*
 * Convert rule type to a printable string.
 */
static const char *rwf_rule_type_name(rwf_match_type type)
{
    switch (type) {
        case RWF_MATCH_EXACT:
            return "exact";

        case RWF_MATCH_PREFIX:
            return "prefix";

        case RWF_MATCH_REGEX:
            return "regex";

        case RWF_MATCH_TARGET_REGEX:
            return "target-regex";

        default:
            return "unknown";
    }
}


/*
 * Validate a rule identifier.
 *
 * Allowed characters:
 *
 *   A-Z
 *   a-z
 *   0-9
 *   _
 *   -
 *   .
 */
static int rwf_valid_rule_name(const char *name)
{
    const unsigned char *p;

    if (name == NULL || *name == '\0') {
        return 0;
    }

    p = (const unsigned char *) name;

    while (*p != '\0') {

        if (!isalnum(*p) &&
            *p != '_' &&
            *p != '-' &&
            *p != '.') {

            return 0;
        }

        ++p;
    }

    return 1;
}


/*
 * Validate policy syntax.
 *
 * Accepted:
 *
 *   off
 *   permanent
 *   3600
 *   30s
 *   30m
 *   4h
 *   3d
 *   2w
 *
 * The policy is forwarded unchanged to the privileged helper, which
 * translates it into the configured firewall action.
 */
static int rwf_valid_policy(const char *policy)
{
    apr_size_t len;
    apr_size_t i;
    apr_size_t digits;

    if (policy == NULL || *policy == '\0') {
        return 0;
    }

    if (strcasecmp(policy, "off") == 0 ||
        strcasecmp(policy, "permanent") == 0) {

        return 1;
    }

    len = strlen(policy);

    if (len == 0) {
        return 0;
    }

    digits = len;

    switch (policy[len - 1]) {
        case 's':
        case 'S':
        case 'm':
        case 'M':
        case 'h':
        case 'H':
        case 'd':
        case 'D':
        case 'w':
        case 'W':
            digits = len - 1;
            break;

        default:
            break;
    }

    if (digits == 0) {
        return 0;
    }

    for (i = 0; i < digits; ++i) {

        if (!isdigit((unsigned char) policy[i])) {
            return 0;
        }
    }

    /*
     * If there was no suffix, all characters must have been digits.
     */
    if (digits == len) {
        return 1;
    }

    /*
     * With suffix, it must be exactly the final character.
     */
    return digits == (len - 1);
}


/*
 * Create configuration for the main server or a VirtualHost.
 */
static void *rwf_create_server_conf(apr_pool_t *pool, server_rec *server)
{
    rwf_server_conf *conf;

    (void) server;

    conf = apr_pcalloc(pool, sizeof(*conf));

    conf->enabled = -1;
    conf->drop_connection = -1;
    conf->suppress_blocked_accesslog = -1;
    conf->helper_socket = NULL;

    conf->whitelist = apr_array_make(
        pool,
        8,
        sizeof(rwf_whitelist_entry)
    );

    conf->rules = apr_array_make(
        pool,
        16,
        sizeof(rwf_rule)
    );

    return conf;
}


/*
 * Merge parent and VirtualHost configuration.
 *
 * Global rules are inherited by VirtualHosts.
 * Rules declared inside a VirtualHost are appended.
 */
static void *rwf_merge_server_conf(apr_pool_t *pool,
                                   void *basev,
                                   void *addv)
{
    rwf_server_conf *base = (rwf_server_conf *) basev;
    rwf_server_conf *add  = (rwf_server_conf *) addv;
    rwf_server_conf *conf;

    conf = apr_pcalloc(pool, sizeof(*conf));

    conf->enabled =
        (add->enabled != -1)
        ? add->enabled
        : base->enabled;

    conf->drop_connection =
        (add->drop_connection != -1)
        ? add->drop_connection
        : base->drop_connection;

    conf->suppress_blocked_accesslog =
        (add->suppress_blocked_accesslog != -1)
        ? add->suppress_blocked_accesslog
        : base->suppress_blocked_accesslog;

    conf->helper_socket =
        (add->helper_socket != NULL)
        ? add->helper_socket
        : base->helper_socket;

    conf->whitelist = apr_array_make(
        pool,
        (base->whitelist != NULL ? base->whitelist->nelts : 0) +
        (add->whitelist  != NULL ? add->whitelist->nelts  : 0) +
        2,
        sizeof(rwf_whitelist_entry)
    );

    if (base->whitelist != NULL) {
        apr_array_cat(conf->whitelist, base->whitelist);
    }

    if (add->whitelist != NULL) {
        apr_array_cat(conf->whitelist, add->whitelist);
    }

    conf->rules = apr_array_make(
        pool,
        (base->rules != NULL ? base->rules->nelts : 0) +
        (add->rules  != NULL ? add->rules->nelts  : 0) +
        4,
        sizeof(rwf_rule)
    );

    if (base->rules != NULL) {
        apr_array_cat(conf->rules, base->rules);
    }

    if (add->rules != NULL) {
        apr_array_cat(conf->rules, add->rules);
    }

    return conf;
}


