/*
 * Empty literal response used for cache hits.
 *
 * ap_custom_response() expects a literal body to start with a double
 * quote. A string containing only that marker therefore produces an
 * empty HTTP 403 body and prevents Apache from invoking ErrorDocument.
 */
#define RWF_CACHE_BLOCK_RESPONSE "\""


/*
 * Shared cache parameters.
 *
 * 2048 buckets x 4 ways = 8192 simultaneously remembered IPs.
 * Each lookup examines at most four entries.
 *
 * The TTL is deliberately short. The cache is only the immediate shield
 * between the first high-confidence match and the future real firewall ban.
 */
#define RWF_CACHE_BUCKETS     2048
#define RWF_CACHE_WAYS        4
#define RWF_CACHE_IP_LEN      64
#define RWF_CACHE_TTL_SECONDS 300


/*
 * Supported rule types.
 */
typedef enum {
    RWF_MATCH_EXACT = 1,
    RWF_MATCH_PREFIX,
    RWF_MATCH_REGEX,
    RWF_MATCH_TARGET_REGEX
} rwf_match_type;


/*
 * One configured RwF rule.
 *
 * name:
 *   Human-readable/internal rule identifier.
 *
 * type:
 *   Exact, Prefix, path Regex or request-target Regex.
 *
 * pattern:
 *   Path or regular expression.
 *
 * policy:
 *   Firewall policy forwarded to the privileged helper when configured.
 *   Examples:
 *
 *     permanent
 *     1h
 *     3d
 *     2w
 *     3600
 *     off
 *
 * regex:
 *   Compiled representation, used by Regex and TargetRegex rules.
 */
typedef struct {
    const char *name;
    rwf_match_type type;
    const char *pattern;
    const char *policy;
    ap_regex_t *regex;
} rwf_rule;


/*
 * One trusted client/network entry.
 *
 * subnet:
 *   APR pre-parsed IPv4/IPv6 network.
 *
 * spec:
 *   Original administrator-facing value, used only for debug logging.
 */
typedef struct {
    apr_ipsubnet_t *subnet;
    const char *spec;
} rwf_whitelist_entry;


/*
 * Per-server / per-vhost configuration.
 *
 * enabled:
 *
 *   -1 = not explicitly configured
 *    0 = disabled
 *    1 = enabled
 */
typedef struct {
    int enabled;
    int drop_connection;
    int suppress_blocked_accesslog;
    const char *helper_socket;
    apr_array_header_t *whitelist;
    apr_array_header_t *rules;
} rwf_server_conf;


/*
 * Per-request timing context.
 *
 * rwf_enter_us / rwf_exit_us delimit only the time spent inside RwF's
 * post_read_request hook.
 *
 * Apache's own r->request_time and the later log_transaction hook let us
 * also observe the time before RwF and the remainder of the Apache request.
 */
typedef struct {
    apr_time_t rwf_enter_us;
    apr_time_t rwf_exit_us;
    const char *outcome;
} rwf_request_ctx;


/*
 * One entry in the shared fast-block cache.
 */
typedef struct {
    char ip[RWF_CACHE_IP_LEN];
    apr_time_t expires_at;
    apr_uint32_t hit_count;
} rwf_cache_entry;


/*
 * Set-associative cache.
 *
 * Hashing selects one bucket and only the four entries in that bucket
 * are inspected. This avoids a full scan while keeping collision handling
 * simple and deterministic.
 */
typedef struct {
    rwf_cache_entry buckets[RWF_CACHE_BUCKETS][RWF_CACHE_WAYS];
} rwf_cache_state;


