/*
 * RwfHelperSocket /absolute/path/to/helper.sock
 *
 * Optional. If unset, RwF behaves exactly as before and no helper event
 * is emitted. The path must fit in sockaddr_un.sun_path.
 */
static const char *rwf_set_helper_socket(cmd_parms *cmd,
                                         void *dummy,
                                         const char *path)
{
    rwf_server_conf *conf;
    struct sockaddr_un addr;

    (void) dummy;

    if (path == NULL || *path == '\0') {
        return "RwF: RwfHelperSocket requires a non-empty absolute path";
    }

    if (path[0] != '/') {
        return apr_psprintf(
            cmd->pool,
            "RwF: RwfHelperSocket path must be absolute: '%s'",
            path
        );
    }

    if (strlen(path) >= sizeof(addr.sun_path)) {
        return apr_psprintf(
            cmd->pool,
            "RwF: RwfHelperSocket path is too long for AF_UNIX: '%s'",
            path
        );
    }

    conf = ap_get_module_config(
        cmd->server->module_config,
        &rwf_module
    );

    conf->helper_socket = apr_pstrdup(cmd->pool, path);

    return NULL;
}


/*
 * RwfWhitelistIP <ip-or-cidr>
 *
 * Examples:
 *
 *   RwfWhitelistIP 192.0.2.10
 *   RwfWhitelistIP 192.0.2.10/32
 *   RwfWhitelistIP 192.0.2.0/24
 *   RwfWhitelistIP 2001:db8::1/128
 *   RwfWhitelistIP 2001:db8::/32
 *
 * A bare address is treated as one exact host (/32 for IPv4, /128 for IPv6).
 * Whitelisted clients bypass both the fast cache and the rule engine and
 * never generate helper events.
 */
static const char *rwf_add_whitelist_ip(cmd_parms *cmd,
                                        void *dummy,
                                        const char *spec)
{
    rwf_server_conf *conf;
    rwf_whitelist_entry *entry;
    apr_ipsubnet_t *subnet;
    apr_status_t rv;

    char *work;
    char *slash;
    const char *mask;

    (void) dummy;

    if (spec == NULL || *spec == '\0') {
        return "RwF: RwfWhitelistIP requires an IP address or CIDR";
    }

    work = apr_pstrdup(cmd->pool, spec);
    slash = strrchr(work, '/');

    if (slash != NULL) {
        *slash = '\0';
        mask = slash + 1;

        if (*work == '\0' || *mask == '\0') {
            return apr_psprintf(
                cmd->pool,
                "RwF: invalid RwfWhitelistIP value '%s'",
                spec
            );
        }
    }
    else {
        /*
         * No mask means an exact host. A colon unambiguously identifies
         * an IPv6 literal for the configuration forms supported here.
         */
        mask = (strchr(work, ':') != NULL) ? "128" : "32";
    }

    subnet = NULL;

    rv = apr_ipsubnet_create(
        &subnet,
        work,
        mask,
        cmd->pool
    );

    if (rv != APR_SUCCESS || subnet == NULL) {
        return apr_psprintf(
            cmd->pool,
            "RwF: invalid RwfWhitelistIP value '%s'",
            spec
        );
    }

    conf = ap_get_module_config(
        cmd->server->module_config,
        &rwf_module
    );

    if (conf == NULL || conf->whitelist == NULL) {
        return "RwF: internal configuration error while adding whitelist entry";
    }

    entry = apr_array_push(conf->whitelist);
    entry->subnet = subnet;
    entry->spec = apr_pstrdup(cmd->pool, spec);

    return NULL;
}


/*
 * Common implementation for adding a rule.
 */
static const char *rwf_add_rule(cmd_parms *cmd,
                                rwf_match_type type,
                                const char *name,
                                const char *pattern,
                                const char *policy)
{
    rwf_server_conf *conf;
    rwf_rule *rule;

    if (!rwf_valid_rule_name(name)) {

        return apr_psprintf(
            cmd->pool,
            "RwF: invalid rule name '%s'. "
            "Allowed characters are letters, numbers, _, - and .",
            name != NULL ? name : ""
        );
    }

    if (pattern == NULL || *pattern == '\0') {

        return apr_psprintf(
            cmd->pool,
            "RwF rule '%s': empty pattern is not allowed",
            name
        );
    }

    if (!rwf_valid_policy(policy)) {

        return apr_psprintf(
            cmd->pool,
            "RwF rule '%s': invalid policy '%s'",
            name,
            policy != NULL ? policy : ""
        );
    }

    /*
     * Exact and prefix rules operate on URI paths.
     * Require a leading slash to avoid accidental malformed rules.
     */
    if ((type == RWF_MATCH_EXACT ||
         type == RWF_MATCH_PREFIX) &&
        pattern[0] != '/') {

        return apr_psprintf(
            cmd->pool,
            "RwF rule '%s': exact/prefix patterns must start with '/'",
            name
        );
    }

    conf = ap_get_module_config(
        cmd->server->module_config,
        &rwf_module
    );

    if (conf == NULL || conf->rules == NULL) {
        return "RwF: internal configuration error while adding rule";
    }

    rule = apr_array_push(conf->rules);

    memset(rule, 0, sizeof(*rule));

    rule->name = apr_pstrdup(cmd->pool, name);
    rule->type = type;
    rule->pattern = apr_pstrdup(cmd->pool, pattern);
    rule->policy = apr_pstrdup(cmd->pool, policy);
    rule->regex = NULL;

    /*
     * Compile regular expressions immediately while Apache is parsing
     * its configuration.
     *
     * A bad expression therefore causes apache2ctl configtest to fail
     * instead of becoming a runtime surprise.
     */
    if (type == RWF_MATCH_REGEX ||
        type == RWF_MATCH_TARGET_REGEX) {

        int rc;
        char error_buffer[256];

        rule->regex = apr_pcalloc(
            cmd->pool,
            sizeof(ap_regex_t)
        );

        rc = ap_regcomp(
            rule->regex,
            rule->pattern,
            AP_REG_ICASE
        );

        if (rc != 0) {

            ap_regerror(
                rc,
                rule->regex,
                error_buffer,
                sizeof(error_buffer)
            );

            /*
             * Remove the partially-created array element.
             */
            conf->rules->nelts--;

            return apr_psprintf(
                cmd->pool,
                "RwF rule '%s': invalid regular expression '%s': %s",
                name,
                pattern,
                error_buffer
            );
        }

        apr_pool_cleanup_register(
            cmd->pool,
            rule->regex,
            rwf_regex_cleanup,
            apr_pool_cleanup_null
        );
    }

    return NULL;
}


